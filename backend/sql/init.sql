  PROCEDURE exec_ignore(p_sql VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION
    WHEN OTHERS THEN
      -- -01430 列已存在, -00955 对象名已存在, -01408 列已被索引
      IF SQLCODE NOT IN (-1430, -955, -1408) THEN
        RAISE;
      END IF;
  END;
