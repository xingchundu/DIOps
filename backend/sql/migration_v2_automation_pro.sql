  DETAIL          VARCHAR2(4000),
  CHECKED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE INDEX IDX_SQL_REG_HASH ON SQL_REGRESSION(SQL_HASH, INSTANCE_ID);

