-- 3. 自动发布 Auto-Publish (SQL/DDL)
-- ============================================================

-- 发布工单
CREATE TABLE PUBLISH_TICKET (
  TICKET_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  TICKET_NO       VARCHAR2(64)  UNIQUE,       -- 工单号 PUB-20260514-001
  TITLE           VARCHAR2(256) NOT NULL,
  TICKET_TYPE     VARCHAR2(32)  NOT NULL,      -- SQL_PUBLISH/DDL_REVIEW
  INSTANCE_ID     NUMBER,
  DB_NAME         VARCHAR2(128),
  SQL_CONTENT     CLOB          NOT NULL,
  ROLLBACK_SQL    CLOB,
  STATUS          VARCHAR2(32)  DEFAULT 'DRAFT', -- DRAFT/REVIEWING/APPROVED/REJECTED/GRAY/RUNNING/DONE/ROLLED_BACK
  GRAY_PERCENT    NUMBER        DEFAULT 0,        -- 灰度比例 0-100
  RISK_LEVEL      VARCHAR2(16),                   -- LOW/MEDIUM/HIGH/CRITICAL
  REVIEW_RESULT   CLOB,                           -- 审核意见JSON
  EXEC_PLAN       CLOB,                           -- 执行计划
  EXEC_RESULT     CLOB,                           -- 执行结果
  SUBMITTED_BY    NUMBER,
  REVIEWED_BY     NUMBER,
  REVIEWED_AT     TIMESTAMP,
  EXECUTED_BY     NUMBER,
  EXECUTED_AT     TIMESTAMP,
  CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP
);
COMMENT ON TABLE PUBLISH_TICKET IS '自动发布工单（SQL/DDL）';
CREATE INDEX IDX_PUB_TICK_STATUS ON PUBLISH_TICKET(STATUS, CREATED_AT DESC);
CREATE INDEX IDX_PUB_TICK_INST ON PUBLISH_TICKET(INSTANCE_ID);

-- 发布审核记录
CREATE TABLE PUBLISH_REVIEW (
  REVIEW_ID    NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  TICKET_ID    NUMBER NOT NULL,
  ACTION       VARCHAR2(32) NOT NULL, -- APPROVE/REJECT/COMMENT/ROLLBACK
  "COMMENT"      VARCHAR2(2000),
  OPERATED_BY  NUMBER,
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE INDEX IDX_PUB_REV_TICK ON PUBLISH_REVIEW(TICKET_ID);

-- DDL审核规则
