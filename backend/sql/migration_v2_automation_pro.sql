-- 2. 自动故障处理 Auto-Fault
-- ============================================================

-- 故障处理策略
CREATE TABLE FAULT_POLICY (
  POLICY_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  POLICY_NAME    VARCHAR2(128) NOT NULL,
  DB_TYPE        VARCHAR2(32)  NOT NULL, -- MYSQL/ORACLE/POSTGRESQL
  FAULT_TYPE     VARCHAR2(64)  NOT NULL, -- REPL_DELAY/REPL_BROKEN/DISK_FULL/TEMP_FULL/FRA_FULL/SESSION_ABNORMAL
  CONDITION_JSON CLOB,                   -- 触发条件JSON
  ACTION_TYPE    VARCHAR2(64)  NOT NULL, -- AUTO_FIX/ALERT_ONLY/MANUAL
  ACTION_SCRIPT  CLOB,                   -- 修复脚本/命令
  ENABLED        NUMBER(1)     DEFAULT 1,
  INSTANCE_IDS   VARCHAR2(4000),         -- 适用实例（空=全部）
  CREATED_BY     NUMBER,
  CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP
);
COMMENT ON TABLE FAULT_POLICY IS '故障自动处理策略';
CREATE INDEX IDX_FAULT_POL_TYPE ON FAULT_POLICY(DB_TYPE, FAULT_TYPE);

-- 故障处理执行记录
CREATE TABLE FAULT_EXEC_LOG (
  LOG_ID         NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  POLICY_ID      NUMBER,
  INSTANCE_ID    NUMBER       NOT NULL,
  FAULT_TYPE     VARCHAR2(64) NOT NULL,
  TRIGGER_SOURCE VARCHAR2(32) DEFAULT 'AUTO',  -- AUTO/MANUAL
  STATUS         VARCHAR2(32) NOT NULL,         -- SUCCESS/FAILED/RUNNING/SKIPPED
  DETAIL         CLOB,
  STARTED_AT     TIMESTAMP    DEFAULT SYSTIMESTAMP,
  FINISHED_AT    TIMESTAMP,
  CREATED_BY     NUMBER,
  CREATED_AT     TIMESTAMP    DEFAULT SYSTIMESTAMP
);
CREATE INDEX IDX_FAULT_LOG_INST ON FAULT_EXEC_LOG(INSTANCE_ID, CREATED_AT DESC);
CREATE INDEX IDX_FAULT_LOG_POL ON FAULT_EXEC_LOG(POLICY_ID);

