-- 1. 自动巡检 Inspect Pro
-- ============================================================

-- 巡检脚本库（支持多数据库类型，模板上传）
CREATE TABLE INSPECT_SCRIPT (
  SCRIPT_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  SCRIPT_NAME    VARCHAR2(128) NOT NULL,
  DB_TYPE        VARCHAR2(32)  NOT NULL, -- ORACLE/MYSQL/POSTGRESQL/DAMENG/GOLDENDB
  CATEGORY       VARCHAR2(64)  NOT NULL, -- HEALTH/RISK/PARAMETER/SPACE/HA
  SCRIPT_CONTENT CLOB,
  VERSION        VARCHAR2(32)  DEFAULT '1.0',
  IS_TEMPLATE    NUMBER(1)     DEFAULT 0,
  ENABLED        NUMBER(1)     DEFAULT 1,
  CREATED_BY     NUMBER,
  CREATED_AT     TIMESTAMP     DEFAULT SYSTIMESTAMP,
  UPDATED_AT     TIMESTAMP     DEFAULT SYSTIMESTAMP
);
COMMENT ON TABLE INSPECT_SCRIPT IS '巡检脚本库（多数据库类型）';
CREATE INDEX IDX_INSP_SCRIPT_TYPE ON INSPECT_SCRIPT(DB_TYPE, CATEGORY);

-- 巡检任务（取代旧 AUTOMATION_INSPECT_BATCH）
CREATE TABLE INSPECT_TASK (
  TASK_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  TASK_NAME      VARCHAR2(128) NOT NULL,
  DB_TYPE        VARCHAR2(32),               -- 为空=全部类型
  INSTANCE_IDS   VARCHAR2(4000),             -- JSON数组
  SCRIPT_IDS     VARCHAR2(4000),             -- JSON数组
  CRON_EXPR      VARCHAR2(64),               -- 定时表达式
  STATUS         VARCHAR2(32) DEFAULT 'IDLE',-- IDLE/RUNNING/DONE/FAILED
  LAST_RUN_AT    TIMESTAMP,
  NEXT_RUN_AT    TIMESTAMP,
  CREATED_BY     NUMBER,
  CREATED_AT     TIMESTAMP    DEFAULT SYSTIMESTAMP
);
COMMENT ON TABLE INSPECT_TASK IS '巡检任务（定时/手动）';

-- 巡检报告（每次执行生成）
CREATE TABLE INSPECT_REPORT (
  REPORT_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  TASK_ID          NUMBER,
  INSTANCE_ID      NUMBER       NOT NULL,
  DB_TYPE          VARCHAR2(32) NOT NULL,
  REPORT_TYPE      VARCHAR2(32) NOT NULL, -- HEALTH/RISK/PARAMETER/SPACE/HA
  OVERALL_SCORE    NUMBER(5,1),
  OVERALL_STATUS   VARCHAR2(16),          -- NORMAL/WARNING/CRITICAL
  SUMMARY          VARCHAR2(4000),
  PAYLOAD          CLOB,                  -- JSON详情
  EXECUTED_AT      TIMESTAMP    DEFAULT SYSTIMESTAMP,
  CREATED_BY       NUMBER,
  CREATED_AT       TIMESTAMP    DEFAULT SYSTIMESTAMP
);
COMMENT ON TABLE INSPECT_REPORT IS '巡检报告（五类）';
CREATE INDEX IDX_INSP_RPT_INST ON INSPECT_REPORT(INSTANCE_ID, REPORT_TYPE, CREATED_AT DESC);
CREATE INDEX IDX_INSP_RPT_TASK ON INSPECT_REPORT(TASK_ID);

-- 巡检问题明细
CREATE TABLE INSPECT_ISSUE (
  ISSUE_ID     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  REPORT_ID    NUMBER       NOT NULL,
  INSTANCE_ID  NUMBER       NOT NULL,
  CATEGORY     VARCHAR2(64) NOT NULL,
  SEVERITY     VARCHAR2(16) NOT NULL, -- CRITICAL/WARNING/INFO
  TITLE        VARCHAR2(256),
  DESCRIPTION  VARCHAR2(4000),
  ADVICE       VARCHAR2(4000),
  METRIC_KEY   VARCHAR2(128),
  METRIC_VALUE VARCHAR2(256),
  THRESHOLD    VARCHAR2(256),
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE INDEX IDX_INSP_ISSUE_RPT ON INSPECT_ISSUE(REPORT_ID);
CREATE INDEX IDX_INSP_ISSUE_INST ON INSPECT_ISSUE(INSTANCE_ID, SEVERITY);

