-- SQL审核记录
CREATE TABLE SQL_AUDIT_RECORD (
  AUDIT_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  INSTANCE_ID    NUMBER,
  SQL_TEXT       CLOB         NOT NULL,
  SQL_HASH       VARCHAR2(64),
  AUDIT_RESULT   CLOB,                    -- JSON: [{rule,severity,message}]
  SCORE          NUMBER(5,1)  DEFAULT 100,
  RISK_LEVEL     VARCHAR2(16),
  SUBMITTED_BY   NUMBER,
  CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE INDEX IDX_SQL_AUDIT_HASH ON SQL_AUDIT_RECORD(SQL_HASH);
CREATE INDEX IDX_SQL_AUDIT_INST ON SQL_AUDIT_RECORD(INSTANCE_ID, CREATED_AT DESC);

-- SQL基线（执行计划固化）
CREATE TABLE SQL_BASELINE (
  BASELINE_ID    NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  SQL_HASH       VARCHAR2(64) NOT NULL,
  SQL_TEXT       CLOB,
  INSTANCE_ID    NUMBER,
  EXEC_PLAN      CLOB,          -- 基线执行计划JSON
  BASELINE_TYPE  VARCHAR2(32) DEFAULT 'FIXED', -- FIXED/APPROVED/EVOLVED
  STATUS         VARCHAR2(32) DEFAULT 'ACTIVE',
  CREATED_BY     NUMBER,
  CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE INDEX IDX_SQL_BASE_HASH ON SQL_BASELINE(SQL_HASH, STATUS);
CREATE UNIQUE INDEX UDX_SQL_BASE_HASH_INST ON SQL_BASELINE(SQL_HASH, INSTANCE_ID);

-- SQL回归分析记录
CREATE TABLE SQL_REGRESSION (
  REGRESSION_ID   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
