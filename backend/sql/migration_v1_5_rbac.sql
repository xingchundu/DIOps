-- ========== 种子：ADMIN = 全部菜单 ==========
INSERT INTO SYS_ROLE_MENU (ROLE_ID, MENU_ID)
SELECT r.ROLE_ID, m.MENU_ID
FROM SYS_ROLE r
CROSS JOIN SYS_MENU m
WHERE r.ROLE_CODE = 'ADMIN'
  AND NOT EXISTS (
    SELECT 1 FROM SYS_ROLE_MENU x WHERE x.ROLE_ID = r.ROLE_ID AND x.MENU_ID = m.MENU_ID
  );

-- DBA/OPS/REVIEWER/DEV：除「用户管理」「角色权限」外全部（可按需在界面调整）
INSERT INTO SYS_ROLE_MENU (ROLE_ID, MENU_ID)
SELECT r.ROLE_ID, m.MENU_ID
FROM SYS_ROLE r
JOIN SYS_MENU m ON m.MENU_PATH NOT IN ('/settings/users', '/settings/roles')
WHERE r.ROLE_CODE IN ('DBA', 'OPS', 'REVIEWER', 'DEV')
  AND NOT EXISTS (
    SELECT 1 FROM SYS_ROLE_MENU x WHERE x.ROLE_ID = r.ROLE_ID AND x.MENU_ID = m.MENU_ID
  );

-- VIEWER：控制台 + 监控 + 告警 + 个人设置（可按需在界面调整）
