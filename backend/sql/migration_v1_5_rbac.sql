-- RBAC: 角色、菜单、角色-菜单关联（与 SYS_USER.ROLE 的 ROLE_CODE 对齐）
-- 全新建库：请执行 init.sql（已包含本脚本等价的表结构与种子数据）。
-- 本文件用于「已有库、尚未建 RBAC 表」的增量升级；执行一次即可。若表已存在可跳过 CREATE 段。

-- ========== SYS_ROLE ==========
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE SYS_ROLE (
    ROLE_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ROLE_CODE     VARCHAR2(32)  NOT NULL UNIQUE,
    ROLE_NAME     VARCHAR2(64)  NOT NULL,
    STATUS        NUMBER(1)     DEFAULT 1 NOT NULL,
    IS_SYSTEM     NUMBER(1)     DEFAULT 0 NOT NULL,
    SORT_ORDER    NUMBER        DEFAULT 0,
    CREATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP,
    UPDATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP
  )';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF; -- ORA-00955: name is already used
END;
/

COMMENT ON TABLE SYS_ROLE IS '系统角色';
COMMENT ON COLUMN SYS_ROLE.IS_SYSTEM IS '1=内置角色，禁止删除';

-- ========== SYS_MENU ==========
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE SYS_MENU (
    MENU_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MENU_PATH     VARCHAR2(256) NOT NULL UNIQUE,
    MENU_NAME     VARCHAR2(64)  NOT NULL,
    PARENT_PATH   VARCHAR2(256),
    ICON          VARCHAR2(64),
    SORT_ORDER    NUMBER        DEFAULT 0,
    CREATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP
  )';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE SYS_MENU IS '侧栏菜单（路径与前端路由一致）';

-- ========== SYS_ROLE_MENU ==========
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE SYS_ROLE_MENU (
    ROLE_ID       NUMBER NOT NULL,
    MENU_ID       NUMBER NOT NULL,
    CONSTRAINT PK_SYS_ROLE_MENU PRIMARY KEY (ROLE_ID, MENU_ID),
    CONSTRAINT FK_SRM_ROLE FOREIGN KEY (ROLE_ID) REFERENCES SYS_ROLE(ROLE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SRM_MENU FOREIGN KEY (MENU_ID) REFERENCES SYS_MENU(MENU_ID) ON DELETE CASCADE
  )';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE SYS_ROLE_MENU IS '角色可访问菜单';

