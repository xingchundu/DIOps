-- 菜单注册
MERGE INTO SYS_MENU t
USING (SELECT '/settings/system-config' AS p FROM DUAL) s ON (t.MENU_PATH = s.p)
WHEN NOT MATCHED THEN INSERT (MENU_PATH, MENU_NAME, SORT_ORDER)
  VALUES ('/settings/system-config', '系统配置', 115);

INSERT INTO SYS_ROLE_MENU (ROLE_ID, MENU_ID)
SELECT r.ROLE_ID, m.MENU_ID
FROM SYS_ROLE r, SYS_MENU m
WHERE r.ROLE_CODE IN ('ADMIN', 'DBA')
  AND m.MENU_PATH = '/settings/system-config'
  AND NOT EXISTS (
    SELECT 1 FROM SYS_ROLE_MENU rm WHERE rm.ROLE_ID = r.ROLE_ID AND rm.MENU_ID = m.MENU_ID
  );

COMMIT;
