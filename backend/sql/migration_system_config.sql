-- F-69 系统配置：全局参数可视化管理
-- 创建 SYS_CONFIG 表，存储平台可配置参数

BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE SYS_CONFIG (
      CONFIG_ID     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      CONFIG_KEY    VARCHAR2(128) NOT NULL UNIQUE,
      CONFIG_VALUE  VARCHAR2(512),
      DEFAULT_VALUE VARCHAR2(512),
      CATEGORY      VARCHAR2(64),
      LABEL         VARCHAR2(128),
      DESCRIPTION   VARCHAR2(512),
      VALUE_TYPE    VARCHAR2(16) DEFAULT ''NUMBER'',
      MIN_VAL       NUMBER,
      MAX_VAL       NUMBER,
      OPTIONS       VARCHAR2(1024),
      UPDATED_BY    NUMBER,
      UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP
    )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

COMMENT ON TABLE SYS_CONFIG IS 'F-69 系统全局配置参数';
COMMENT ON COLUMN SYS_CONFIG.VALUE_TYPE IS 'NUMBER/STRING/BOOLEAN/SELECT';

-- 种子数据：采集频率
MERGE INTO SYS_CONFIG t USING (SELECT 'monitor.collect.interval_ms' AS k FROM DUAL) s
ON (t.CONFIG_KEY = s.k)
WHEN NOT MATCHED THEN INSERT (CONFIG_KEY, CONFIG_VALUE, DEFAULT_VALUE, CATEGORY, LABEL, DESCRIPTION, VALUE_TYPE, MIN_VAL, MAX_VAL)
  VALUES ('monitor.collect.interval_ms', '90000', '90000', '采集频率', '监控采集间隔(ms)', '周期性采集监控指标的时间间隔，最小60000ms', 'NUMBER', 60000, 3600000);

