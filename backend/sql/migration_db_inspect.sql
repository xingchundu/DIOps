-- ============================================================================
-- 数据库巡检中心（检查项 → 模板 → 计划 → 记录 → 问题项 → 报告）数据模型 —— 可重复执行
-- 对应设计：docs/DB_INSPECT_DESIGN.md
--   覆盖 Oracle / MySQL(GoldenDB) / PostgreSQL(磐维) / 达梦 DM 四个方言族；
--   “采集只取数，判定由规则引擎完成”：DBI_CHECK_IMPL 存各方言的采集 SQL，DBI_CHECK_ITEM 存判定规则与默认阈值。
--   内置检查项 / 模板由 Node 启动时按 ITEM_CODE 幂等写入（不覆盖用户改过的阈值与自定义采集 SQL）。
-- 执行：sqlplus user/pwd@db @migration_db_inspect.sql
-- ============================================================================
SET SERVEROUTPUT ON
SET DEFINE OFF

CREATE OR REPLACE PROCEDURE DBI_EXEC_IGNORE(p_sql IN VARCHAR2) IS
BEGIN
  EXECUTE IMMEDIATE p_sql;
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE NOT IN (-955, -1430, -1408, -2275, -2260, -2261, -1442, -942, -1451) THEN RAISE; END IF;
END;
/

-- ---------------------------------------------------------------- 检查项
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_CHECK_ITEM (
  ITEM_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ITEM_CODE    VARCHAR2(64 CHAR)  NOT NULL,           -- 稳定编码，如 storage.tablespace / sql.slow_avg
  ITEM_NAME    VARCHAR2(128 CHAR) NOT NULL,
  CATEGORY     VARCHAR2(32)  NOT NULL,                -- AVAILABILITY/RESOURCE/STORAGE/PERFORMANCE/SQL/HA/BACKUP/CONFIG/SECURITY/LOG
  DESCRIPTION  VARCHAR2(512 CHAR),
  RULE_TYPE    VARCHAR2(16)  NOT NULL,                -- THRESHOLD(数值阈值) / ROWS(有行即异常) / STATUS(状态值) / TOPN(只展示不判定) / INFO
  RULE_JSON    CLOB,                                  -- {direction,unit,ok:[],bad:[],level,nullLevel,maxFindings,objLabel,minExecs...}
  WARN_VALUE   NUMBER,                                -- 默认警告阈值（全局）
  CRIT_VALUE   NUMBER,                                -- 默认严重阈值（全局）
  ADVICE       VARCHAR2(1024 CHAR),
  SQL_BEARING  NUMBER(1) DEFAULT 0,                   -- 1=结果行是 SQL，必须带 sql_id（原生 SQL_ID / queryid / digest，缺失则 FP: 指纹）
  BUILTIN      NUMBER(1) DEFAULT 0,
  ENABLED      NUMBER(1) DEFAULT 1,
  SORT_NO      NUMBER DEFAULT 100,
  CREATED_BY   NUMBER,
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP
)]'); END;
/
BEGIN DBI_EXEC_IGNORE('CREATE UNIQUE INDEX UX_DBI_ITEM_CODE ON DBI_CHECK_ITEM(ITEM_CODE)'); END;
/

-- 各方言采集实现：一个检查项 × 一个方言族 = 一行
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_CHECK_IMPL (
  IMPL_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ITEM_ID      NUMBER NOT NULL,
  DB_FAMILY    VARCHAR2(16) NOT NULL,                 -- ORACLE / MYSQL / POSTGRESQL / DAMENG（GOLDENDB→MYSQL，PANWEI→POSTGRESQL）
  SQL_TEXT     CLOB NOT NULL,                         -- 只读 SELECT/WITH/SHOW；可含 {{TOPN}} {{DAYS}} 占位
  FALLBACK_SQL CLOB,                                  -- JSON 数组：主 SQL 失败（版本差异/视图不存在）时依次尝试
  COL_MAP      VARCHAR2(1024 CHAR),                   -- JSON：列名映射，如 {"val":["Seconds_Behind_Source","Seconds_Behind_Master"]}
  ADAPTIVE     VARCHAR2(32),                          -- 自适应取数（探测实际列名后拼 SQL），如 DM_SQL_STAT:elapsed
  DB_TYPES     VARCHAR2(128),                         -- JSON 数组：限定只对这些具体库类型生效（如 ["PANWEI"]），空=整个方言族
  UNIT         VARCHAR2(16 CHAR),                     -- 本方言结果单位（覆盖检查项单位）
  WARN_VALUE   NUMBER,                                -- 本方言默认阈值（各库单位不同时使用）
  CRIT_VALUE   NUMBER,
  IS_CUSTOM    NUMBER(1) DEFAULT 0,                   -- 1=用户在“高级”里改过，重新写入内置目录时不覆盖
  ENABLED      NUMBER(1) DEFAULT 1,
  UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT UK_DBI_IMPL UNIQUE (ITEM_ID, DB_FAMILY),
  CONSTRAINT FK_DBI_IMPL_ITEM FOREIGN KEY (ITEM_ID) REFERENCES DBI_CHECK_ITEM(ITEM_ID) ON DELETE CASCADE
)]'); END;
/

-- 阈值与范围：全局 < 方言族/库类型 < 环境 < 业务线 < 实例（越具体越优先）
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_THRESHOLD (
  THR_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ITEM_ID      NUMBER NOT NULL,
  SCOPE_TYPE   VARCHAR2(16) NOT NULL,                 -- DB_TYPE / ENV / BIZ_LINE / INSTANCE
  SCOPE_VALUE  VARCHAR2(128 CHAR) NOT NULL,
  WARN_VALUE   NUMBER,
  CRIT_VALUE   NUMBER,
  ENABLED      NUMBER(1) DEFAULT 1,                   -- 0=该范围内不检查此项
  UPDATED_BY   NUMBER,
  UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT UK_DBI_THR UNIQUE (ITEM_ID, SCOPE_TYPE, SCOPE_VALUE),
  CONSTRAINT FK_DBI_THR_ITEM FOREIGN KEY (ITEM_ID) REFERENCES DBI_CHECK_ITEM(ITEM_ID) ON DELETE CASCADE
)]'); END;
/

-- ---------------------------------------------------------------- 模板
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_TEMPLATE (
  TEMPLATE_ID   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  TEMPLATE_CODE VARCHAR2(64 CHAR) NOT NULL,
  TEMPLATE_NAME VARCHAR2(128 CHAR) NOT NULL,
  KIND          VARCHAR2(16) DEFAULT 'DAILY',         -- DAILY 日常 / SPECIAL 专项 / BASELINE 基线
  DB_FAMILIES   VARCHAR2(256),                        -- JSON 数组；为空=全部方言
  DESCRIPTION   VARCHAR2(512 CHAR),
  ALERT_RULES   VARCHAR2(1024 CHAR),                  -- JSON 数组：告警规则名/关键字，命中后联动触发本模板（专项）
  BUILTIN       NUMBER(1) DEFAULT 0,
  ENABLED       NUMBER(1) DEFAULT 1,
  CREATED_BY    NUMBER,
  CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP
)]'); END;
/
BEGIN DBI_EXEC_IGNORE('CREATE UNIQUE INDEX UX_DBI_TPL_CODE ON DBI_TEMPLATE(TEMPLATE_CODE)'); END;
/
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_TEMPLATE_ITEM (
  TEMPLATE_ID  NUMBER NOT NULL,
  ITEM_ID      NUMBER NOT NULL,
  SORT_NO      NUMBER DEFAULT 0,                      -- 执行顺序
  CONSTRAINT PK_DBI_TPL_ITEM PRIMARY KEY (TEMPLATE_ID, ITEM_ID),
  CONSTRAINT FK_DBI_TI_TPL  FOREIGN KEY (TEMPLATE_ID) REFERENCES DBI_TEMPLATE(TEMPLATE_ID) ON DELETE CASCADE,
  CONSTRAINT FK_DBI_TI_ITEM FOREIGN KEY (ITEM_ID)     REFERENCES DBI_CHECK_ITEM(ITEM_ID)   ON DELETE CASCADE
)]'); END;
/

-- ---------------------------------------------------------------- 计划
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_PLAN (
  PLAN_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  PLAN_NAME    VARCHAR2(128 CHAR) NOT NULL,
  TEMPLATE_ID  NUMBER NOT NULL,
  SCOPE_JSON   VARCHAR2(4000),                        -- {"dbTypes":[],"envs":[],"bizLines":[],"instanceIds":[]}，空=全部纳管实例
  CRON_EXPR    VARCHAR2(64),                          -- 为空=仅手动执行
  WINDOW_START VARCHAR2(5),                           -- HH:mm 执行窗口，到点不在窗口内则跳过；支持跨午夜
  WINDOW_END   VARCHAR2(5),
  ENABLED      NUMBER(1) DEFAULT 1,
  LAST_RUN_ID  NUMBER,
  LAST_RUN_AT  TIMESTAMP,
  CREATED_BY   NUMBER,
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP
)]'); END;
/

-- ---------------------------------------------------------------- 巡检记录（一次触发一条，按实例拆子任务）
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_RUN (
  RUN_ID         NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  PLAN_ID        NUMBER,
  PLAN_NAME      VARCHAR2(128 CHAR),
  TEMPLATE_ID    NUMBER,
  TEMPLATE_NAME  VARCHAR2(128 CHAR),
  TRIGGER_TYPE   VARCHAR2(16) NOT NULL,               -- SCHEDULE 定时 / MANUAL 手动 / ALERT 告警联动 / RECHECK 复检
  TRIGGER_REF    VARCHAR2(128 CHAR),                  -- 告警ID / 问题项ID
  ONLY_ITEM_CODE VARCHAR2(64 CHAR),                   -- 复检时只跑这一项
  STATUS         VARCHAR2(16) DEFAULT 'RUNNING',      -- RUNNING / SUCCESS / PARTIAL / FAILED
  TOTAL_INST     NUMBER DEFAULT 0,
  DONE_INST      NUMBER DEFAULT 0,
  OK_INST        NUMBER DEFAULT 0,
  FAIL_INST      NUMBER DEFAULT 0,                    -- 采集失败（连不上/整体异常），单独统计为“巡检失败”，不计入异常
  CRIT_CNT       NUMBER DEFAULT 0,
  WARN_CNT       NUMBER DEFAULT 0,
  MESSAGE        VARCHAR2(1000 CHAR),
  STARTED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP,
  FINISHED_AT    TIMESTAMP,
  CREATED_BY     NUMBER,
  CREATED_NAME   VARCHAR2(64 CHAR)
)]'); END;
/
BEGIN DBI_EXEC_IGNORE('CREATE INDEX IDX_DBI_RUN_START ON DBI_RUN(STARTED_AT DESC)'); END;
/
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_RUN_INSTANCE (
  RUN_ID        NUMBER NOT NULL,
  INSTANCE_ID   NUMBER NOT NULL,
  INSTANCE_NAME VARCHAR2(128 CHAR),
  DB_TYPE       VARCHAR2(32),
  HOST_IP       VARCHAR2(64),
  EXEC_STATUS   VARCHAR2(16) DEFAULT 'RUNNING',       -- RUNNING / OK / FAILED
  ERROR_MSG     VARCHAR2(1000 CHAR),
  ITEMS_TOTAL   NUMBER DEFAULT 0,
  ITEMS_OK      NUMBER DEFAULT 0,
  ITEMS_ERR     NUMBER DEFAULT 0,                     -- 单个检查项采集失败（权限不足/视图不存在），不计入异常
  ITEMS_NA      NUMBER DEFAULT 0,                     -- 该方言无采集实现 / 未启用
  CRIT_CNT      NUMBER DEFAULT 0,
  WARN_CNT      NUMBER DEFAULT 0,
  SCORE         NUMBER(5,1),
  DURATION_MS   NUMBER,
  CONSTRAINT PK_DBI_RUN_INST PRIMARY KEY (RUN_ID, INSTANCE_ID)
)]'); END;
/
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_RUN_RESULT (
  RESULT_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  RUN_ID         NUMBER NOT NULL,
  INSTANCE_ID    NUMBER NOT NULL,
  ITEM_ID        NUMBER,
  ITEM_CODE      VARCHAR2(64 CHAR) NOT NULL,
  ITEM_NAME      VARCHAR2(128 CHAR),
  CATEGORY       VARCHAR2(32),
  STATUS         VARCHAR2(16) NOT NULL,               -- OK / WARNING / CRITICAL / INFO / NA / ERROR
  WORST_VALUE    VARCHAR2(128 CHAR),
  THRESHOLD_TEXT VARCHAR2(128 CHAR),
  ROW_COUNT      NUMBER,
  MESSAGE        VARCHAR2(1000 CHAR),
  EVIDENCE       CLOB,                                -- JSON {columns,rows(≤50),truncated}
  DURATION_MS    NUMBER
)]'); END;
/
BEGIN DBI_EXEC_IGNORE('CREATE INDEX IDX_DBI_RES_RUN ON DBI_RUN_RESULT(RUN_ID, INSTANCE_ID)'); END;
/

-- ---------------------------------------------------------------- 问题项（同实例同检查项同对象只保留一条“当前问题”）
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_ISSUE (
  ISSUE_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  INSTANCE_ID   NUMBER NOT NULL,
  INSTANCE_NAME VARCHAR2(128 CHAR),
  DB_TYPE       VARCHAR2(32),
  HOST_IP       VARCHAR2(64),
  ITEM_ID       NUMBER,
  ITEM_CODE     VARCHAR2(64 CHAR) NOT NULL,
  ITEM_NAME     VARCHAR2(128 CHAR),
  CATEGORY      VARCHAR2(32),
  OBJECT_KEY    VARCHAR2(256 CHAR) DEFAULT '-' NOT NULL, -- 对象：表空间名/会话/sql_id…
  SEVERITY      VARCHAR2(16) NOT NULL,                -- CRITICAL / WARNING
  TITLE         VARCHAR2(512 CHAR),
  CURRENT_VALUE VARCHAR2(128 CHAR),
  THRESHOLD_TEXT VARCHAR2(128 CHAR),
  EVIDENCE      CLOB,                                 -- JSON 证据行
  ADVICE        VARCHAR2(1024 CHAR),
  SQL_ID        VARCHAR2(128 CHAR),                   -- SQL 类问题：原生 SQL_ID / queryid / digest（缺失为 FP:指纹）
  SQL_ID_KIND   VARCHAR2(16),                         -- SQL_ID / QUERYID / DIGEST / FINGERPRINT
  SQL_TEXT      VARCHAR2(2000 CHAR),
  STATUS        VARCHAR2(16) DEFAULT 'OPEN' NOT NULL, -- OPEN 待处理 / FIXING 整改中 / FIXED 已整改 / IGNORED 已忽略
  NOTE          VARCHAR2(512 CHAR),
  FIRST_RUN_ID  NUMBER,
  LAST_RUN_ID   NUMBER,
  OCCURRENCES   NUMBER DEFAULT 1,
  FIRST_SEEN    TIMESTAMP DEFAULT SYSTIMESTAMP,
  LAST_SEEN     TIMESTAMP DEFAULT SYSTIMESTAMP,
  FIXED_AT      TIMESTAMP,
  HANDLED_BY    VARCHAR2(64 CHAR)
)]'); END;
/
-- 未整改的“当前问题”唯一（函数索引：FIXED 的历史行不受限）
BEGIN DBI_EXEC_IGNORE(q'[CREATE UNIQUE INDEX UX_DBI_ISSUE_CUR ON DBI_ISSUE (
  CASE WHEN STATUS <> 'FIXED' THEN INSTANCE_ID END,
  CASE WHEN STATUS <> 'FIXED' THEN ITEM_CODE END,
  CASE WHEN STATUS <> 'FIXED' THEN OBJECT_KEY END)]'); END;
/
BEGIN DBI_EXEC_IGNORE('CREATE INDEX IDX_DBI_ISSUE_INST ON DBI_ISSUE(INSTANCE_ID, STATUS, SEVERITY)'); END;
/
BEGIN DBI_EXEC_IGNORE('CREATE INDEX IDX_DBI_ISSUE_SQLID ON DBI_ISSUE(SQL_ID)'); END;
/

-- ---------------------------------------------------------------- SQL 洞察快照（每次巡检的 Top SQL / 问题 SQL，每条都带 sql_id）
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_SQL_SNAPSHOT (
  SNAP_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  RUN_ID         NUMBER NOT NULL,
  INSTANCE_ID    NUMBER NOT NULL,
  DB_TYPE        VARCHAR2(32),
  DB_FAMILY      VARCHAR2(16),
  ITEM_CODE      VARCHAR2(64 CHAR) NOT NULL,          -- 来自哪个检查项（sql.top_elapsed / sql.slow_avg / …）
  DIMENSION      VARCHAR2(24),                        -- ELAPSED / CPU / IO / EXECS / SLOW / FULLSCAN / PLAN_CHANGE / NO_BIND / LONG_RUN / LOCK / TX
  RANK_NO        NUMBER,
  SQL_ID         VARCHAR2(128 CHAR) NOT NULL,
  SQL_ID_KIND    VARCHAR2(16),
  PLAN_HASH      VARCHAR2(64),
  SCHEMA_NAME    VARCHAR2(128 CHAR),
  EXECS          NUMBER,
  TOTAL_MS       NUMBER,
  AVG_MS         NUMBER,
  CPU_MS         NUMBER,
  LOGICAL_READS  NUMBER,
  PHYSICAL_READS NUMBER,
  ROWS_PROC      NUMBER,
  ROWS_EXAMINED  NUMBER,                              -- MySQL 扫描行数
  METRIC_VALUE   NUMBER,                              -- 本检查项的判定值（如平均耗时 / 表大小 / 等待秒）
  SEVERITY       VARCHAR2(16),                        -- 判定结果：CRITICAL / WARNING / OK
  LAST_ACTIVE    VARCHAR2(32),
  SQL_TEXT       VARCHAR2(2000 CHAR),
  EXTRA          CLOB
)]'); END;
/
BEGIN DBI_EXEC_IGNORE('CREATE INDEX IDX_DBI_SNAP_RUN ON DBI_SQL_SNAPSHOT(RUN_ID, INSTANCE_ID, ITEM_CODE)'); END;
/
BEGIN DBI_EXEC_IGNORE('CREATE INDEX IDX_DBI_SNAP_SQLID ON DBI_SQL_SNAPSHOT(SQL_ID, INSTANCE_ID)'); END;
/

-- ---------------------------------------------------------------- 报告（每次巡检一份，文件按需生成）
BEGIN DBI_EXEC_IGNORE(q'[
CREATE TABLE DBI_REPORT (
