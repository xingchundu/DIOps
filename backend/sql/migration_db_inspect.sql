  REPORT_NAME    VARCHAR2(256 CHAR),
  TRIGGER_TYPE   VARCHAR2(16),
  INSTANCE_COUNT NUMBER DEFAULT 0,
  ABNORMAL_INST  NUMBER DEFAULT 0,
  FAIL_INST      NUMBER DEFAULT 0,
  CRIT_CNT       NUMBER DEFAULT 0,
  WARN_CNT       NUMBER DEFAULT 0,
  OPEN_ISSUES    NUMBER DEFAULT 0,
  STATUS         VARCHAR2(16) DEFAULT 'DONE',
  WORD_FILE      VARCHAR2(512),
  EXCEL_FILE     VARCHAR2(512),
  CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT UK_DBI_REPORT_RUN UNIQUE (RUN_ID)
)]'); END;
/

-- ---------------------------------------------------------------- 菜单（ADMIN 自动可见；DBA/OPS 授权）
MERGE INTO SYS_MENU t
USING (SELECT '/db-inspect' AS p FROM DUAL) s ON (t.MENU_PATH = s.p)
WHEN NOT MATCHED THEN INSERT (MENU_PATH, MENU_NAME, SORT_ORDER) VALUES ('/db-inspect', '数据库巡检', 65);

INSERT INTO SYS_ROLE_MENU (ROLE_ID, MENU_ID)
SELECT r.ROLE_ID, m.MENU_ID FROM SYS_ROLE r CROSS JOIN SYS_MENU m
WHERE r.ROLE_CODE IN ('ADMIN', 'DBA', 'OPS', 'REVIEWER') AND m.MENU_PATH = '/db-inspect'
  AND NOT EXISTS (SELECT 1 FROM SYS_ROLE_MENU x WHERE x.ROLE_ID = r.ROLE_ID AND x.MENU_ID = m.MENU_ID);

COMMIT;
