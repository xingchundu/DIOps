-- ============================================================
-- v5：知识图谱 / Oracle SQL_ID 深度诊断 / SQL 优化记录增强 / 巡检联动
-- 可重复执行（已存在则跳过）。执行用户：平台库账号（与 init.sql 相同）
-- ============================================================

CREATE OR REPLACE PROCEDURE DI_EXEC_IGNORE(p_sql IN VARCHAR2) IS
BEGIN
  EXECUTE IMMEDIATE p_sql;
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE NOT IN (-955, -1430, -1408, -2275, -2260, -2261, -1442, -942) THEN RAISE; END IF;
END;
/

-- ---------------------------------------------------------------- 知识图谱：节点
-- NODE_TYPE：INSTANCE / SQL / TABLE / FINDING(问题) / INSPECTION(巡检) / RCA / CAUSE(根因) / ACTION(处置建议) / OPT(SQL优化) / DIAG(SQL_ID诊断) / KNOWLEDGE(知识文档) / TAG / NOTE
BEGIN DI_EXEC_IGNORE(q'[
CREATE TABLE AI_KG_NODE (
  NODE_ID     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NODE_TYPE   VARCHAR2(32)   NOT NULL,
  NODE_KEY    VARCHAR2(400)  NOT NULL,           -- 同类型内唯一的业务键（如 INSTANCE:12、SQL:<md5>、FINDING:SPACE|表空间使用率偏高）
  LABEL       VARCHAR2(400),
  PROPS       CLOB,                              -- JSON：详情/最近一次证据
  WEIGHT      NUMBER DEFAULT 1,                  -- 出现次数（热度）
  SOURCE      VARCHAR2(32),                      -- INSPECT / SQL_OPT / RCA / DIAG / KB / MANUAL / ALERT
  REF_ID      NUMBER,                            -- 关联业务表主键（报告ID/优化记录ID/RCA_ID/DOC_ID …）
  CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT UK_KG_NODE UNIQUE (NODE_TYPE, NODE_KEY)
)]'); END;
/
BEGIN DI_EXEC_IGNORE('CREATE INDEX IDX_KG_NODE_LABEL ON AI_KG_NODE (NODE_TYPE, LABEL)'); END;
/
BEGIN DI_EXEC_IGNORE('CREATE INDEX IDX_KG_NODE_UPD ON AI_KG_NODE (UPDATED_AT)'); END;
/

-- ---------------------------------------------------------------- 知识图谱：关系
-- REL_TYPE：OF_INSTANCE / HAS_FINDING / FOUND / RUNS_ON / ACCESSES / OPTIMIZES / SUGGESTS / CAUSED_BY / FIXED_BY / DIAGNOSES / DESCRIBES / TAGGED / RELATED
BEGIN DI_EXEC_IGNORE(q'[
CREATE TABLE AI_KG_EDGE (
  EDGE_ID     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  SRC_ID      NUMBER NOT NULL,
  DST_ID      NUMBER NOT NULL,
  REL_TYPE    VARCHAR2(48) NOT NULL,
  WEIGHT      NUMBER DEFAULT 1,
  PROPS       CLOB,
  CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT UK_KG_EDGE UNIQUE (SRC_ID, DST_ID, REL_TYPE),
  CONSTRAINT FK_KG_EDGE_SRC FOREIGN KEY (SRC_ID) REFERENCES AI_KG_NODE(NODE_ID) ON DELETE CASCADE,
  CONSTRAINT FK_KG_EDGE_DST FOREIGN KEY (DST_ID) REFERENCES AI_KG_NODE(NODE_ID) ON DELETE CASCADE
)]'); END;
/
BEGIN DI_EXEC_IGNORE('CREATE INDEX IDX_KG_EDGE_SRC ON AI_KG_EDGE (SRC_ID)'); END;
/
BEGIN DI_EXEC_IGNORE('CREATE INDEX IDX_KG_EDGE_DST ON AI_KG_EDGE (DST_ID)'); END;
/

-- ---------------------------------------------------------------- Oracle SQL_ID 深度诊断任务（orasqlx）
BEGIN DI_EXEC_IGNORE(q'[
CREATE TABLE SQL_DIAG_JOB (
  JOB_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  INSTANCE_ID  NUMBER        NOT NULL,
  SQL_ID       VARCHAR2(32)  NOT NULL,
  OPTIONS      CLOB,                              -- JSON：pdb / awrDays / noAwr …
  STATUS       VARCHAR2(16)  DEFAULT 'PENDING',   -- PENDING / RUNNING / DONE / FAILED
  DOCX_FILE    VARCHAR2(512),
  HTML_FILE    VARCHAR2(512),
  JSON_FILE    VARCHAR2(512),
  SUMMARY      CLOB,                              -- JSON：findings / 关键指标
  FINDING_CNT  NUMBER,
  ERR_MSG      VARCHAR2(2000),
  ASSET_ID     NUMBER,                            -- 关联 SQL 洞察资产（DI_SQL_ASSET）
  CREATED_BY   NUMBER,
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP,
  FINISHED_AT  TIMESTAMP
)]'); END;
/
BEGIN DI_EXEC_IGNORE('CREATE INDEX IDX_DIAG_INST ON SQL_DIAG_JOB (INSTANCE_ID, SQL_ID, CREATED_AT)'); END;
/

-- ---------------------------------------------------------------- SQL 优化记录增强：目标实例 / 优化方式（规则 or AI）/ 预检结果
BEGIN DI_EXEC_IGNORE('ALTER TABLE SQL_OPT_HISTORY ADD (INSTANCE_ID NUMBER)'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE SQL_OPT_HISTORY ADD (OPT_MODE VARCHAR2(16))'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE SQL_OPT_HISTORY ADD (PRECHECK CLOB)'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE SQL_OPT_HISTORY ADD (BASELINE_MS NUMBER)'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE SQL_OPT_HISTORY ADD (AFTER_MS NUMBER)'); END;
/

COMMENT ON TABLE AI_KG_NODE IS 'AI 知识图谱：节点（实例/SQL/问题/根因/处置建议/文档…）';
COMMENT ON TABLE AI_KG_EDGE IS 'AI 知识图谱：关系';
COMMENT ON TABLE SQL_DIAG_JOB IS 'Oracle SQL_ID 深度诊断任务（orasqlx）';

DROP PROCEDURE DI_EXEC_IGNORE;
