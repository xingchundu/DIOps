-- ============================================================================
-- migration_security_fixes.sql —— 代码审查修复配套的表结构调整（已有库执行；可重复执行）
--
--   1. CMDB_INSTANCE.DB_PASSWORD 加长到 1024：凭据改为 AES-256-GCM 加密（AESGCM:v1:base64），
--      密文比原来的 Base64 长，256 不够用。存量 Base64 密码由 Java 服务启动时自动迁移为密文
--      （SecretsMigrator，需先配置 DBOPS_SECRET_KEY）。
--   2. CMDB_HOST 补齐 SSH_* 列（init.sql 建表原来不含，只在 migration_monitor_catalog_phase3 里）。
--   3. FAULT_EXEC_LOG.HA_CORRELATION_ID、SQL_AUDIT_RECORD / SQL_REVIEW_TICKET.ASSET_ID：
--      init.sql 原来缺这几列（只在 migration 里），全新库初始化中断 / 评审工单去重失效。
--   4. 发布工单新增中间状态 EXECUTING / ROLLING_BACK（VARCHAR2(32) 已够，无需改列）。
--
-- 执行：sqlplus user/pwd@db @migration_security_fixes.sql
-- ============================================================================

CREATE OR REPLACE PROCEDURE DI_EXEC_IGNORE(p_sql IN VARCHAR2) IS
BEGIN
  EXECUTE IMMEDIATE p_sql;
EXCEPTION WHEN OTHERS THEN
  -- 已存在的对象 / 列 / 索引，以及列已经足够长等情况忽略
  IF SQLCODE NOT IN (-955, -1430, -1408, -2275, -2260, -2261, -1442, -942, -1451) THEN RAISE; END IF;
END;
/

-- 1. 加密凭据列长度
BEGIN DI_EXEC_IGNORE('ALTER TABLE CMDB_INSTANCE MODIFY (DB_PASSWORD VARCHAR2(1024))'); END;
/
COMMENT ON COLUMN CMDB_INSTANCE.DB_PASSWORD IS 'AES-256-GCM 加密存储（AESGCM:v1:...，密钥 DBOPS_SECRET_KEY）';

-- 2. CMDB_HOST SSH 列
BEGIN DI_EXEC_IGNORE('ALTER TABLE CMDB_HOST ADD (SSH_ENABLED NUMBER(1) DEFAULT 0)'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE CMDB_HOST ADD (SSH_PORT NUMBER DEFAULT 22)'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE CMDB_HOST ADD (SSH_USER VARCHAR2(128))'); END;
/
BEGIN DI_EXEC_IGNORE(q'[ALTER TABLE CMDB_HOST ADD (SSH_AUTH_TYPE VARCHAR2(16) DEFAULT 'PASSWORD')]'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE CMDB_HOST ADD (SSH_PASSWORD VARCHAR2(1024))'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE CMDB_HOST MODIFY (SSH_PASSWORD VARCHAR2(1024))'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE CMDB_HOST ADD (SSH_PRIVATE_KEY CLOB)'); END;
/

-- 3. init.sql 与 migration 脱节的列
BEGIN DI_EXEC_IGNORE('ALTER TABLE FAULT_EXEC_LOG ADD (HA_CORRELATION_ID NUMBER)'); END;
/
BEGIN DI_EXEC_IGNORE('CREATE INDEX IDX_FAULT_LOG_HA ON FAULT_EXEC_LOG(HA_CORRELATION_ID)'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE SQL_AUDIT_RECORD ADD (ASSET_ID NUMBER)'); END;
/
BEGIN DI_EXEC_IGNORE('CREATE INDEX IDX_AUDIT_ASSET ON SQL_AUDIT_RECORD(ASSET_ID)'); END;
/
BEGIN DI_EXEC_IGNORE('ALTER TABLE SQL_REVIEW_TICKET ADD (ASSET_ID NUMBER)'); END;
/
BEGIN DI_EXEC_IGNORE('CREATE INDEX IDX_SRT_ASSET ON SQL_REVIEW_TICKET(ASSET_ID, STATUS)'); END;
/

-- 4. 表达式唯一索引已存在时保持不变（DI_SQL_PROBLEM 的 SKIPPED/OPEN 处理顺序已在代码中调整）

DROP PROCEDURE DI_EXEC_IGNORE;

PROMPT migration_security_fixes 完成
